import numpy as np
import matplotlib.pyplot as plt

'''
Semua angka dinyatakan dalam satuan SI
'''

# Parameter-parameter umum
m = 1 # massa benda
k = 1 # konstanta pegas
r = 0.01 # radius benda

# Fungsi ODE
def f_system(t, state, gamma, omega_sq):
    x, v = state
    dxdt = v
    dvdt = -gamma * v - omega_sq * x
    return np.array([dxdt, dvdt])

# Fungsi Runge-Kutta Orde 4
def runge_kutta_4_system(f, state0, t0, t_end, dt, gamma, omega_sq):
    n = int((t_end - t0) / dt) + 1
    t_values = np.linspace(t0, t_end, n)
    states = np.zeros((n, len(state0)))
    states[0] = state0

    for i in range(1, n):
        t = t_values[i-1]
        state = states[i-1]

        k1 = dt * f(t, state, gamma, omega_sq)
        k2 = dt * f(t + 0.5 * dt, state + 0.5 * k1, gamma, omega_sq)
        k3 = dt * f(t + 0.5 * dt, state + 0.5 * k2, gamma, omega_sq)
        k4 = dt * f(t + dt, state + k3, gamma, omega_sq)

        states[i] = state + (k1 + 2*k2 + 2*k3 + k4) / 6

    return t_values, states

# Kondisi awal
x0 = 0.1 # Posisi
v0 = 0 # Kecepatan
state0 = np.array([x0, v0])

# Parameter waktu
t0 = 0 # Start
t_end = 100 # End
dt = 0.01 # Element

# Hitung untuk viskositas 4 Poise
zeta1 = 4 * 0.1
gamma1 = 6 * np.pi * zeta1 * r / m
omega_sq = k / m
t_values1, states1 = runge_kutta_4_system(f_system, state0, t0, t_end, dt, gamma1, omega_sq)

# Hitung untuk viskositas 2 Poise
zeta2 = 2 * 0.1
gamma2 = 6 * np.pi * zeta2 * r / m
t_values2, states2 = runge_kutta_4_system(f_system, state0, t0, t_end, dt, gamma2, omega_sq)

# Posisi (x) untuk kedua viskositas
x_values1 = states1[:, 0]
x_values2 = states2[:, 0]

# Plot kurva
plt.figure(figsize=(12, 6))
plt.plot(t_values1, x_values1, label='Viskositas 4 Poise', color='b')
plt.plot(t_values2, x_values2, label='Viskositas 2 Poise', color='r')
plt.xlabel('Waktu (t) dalam detik')
plt.ylabel('Posisi (x) dalam meter')
plt.title('Osilasi Teredam dalam Medium Viskos dengan Berbeda Viskositas (Runge-Kutta 4)')
plt.grid(True)
plt.legend()
plt.show()